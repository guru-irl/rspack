import assert from 'node:assert/strict';
import { EventEmitter } from 'node:events';
import { triggerCapture, edgeContract } from './trigger-capture.mjs';
const hooks=()=>Object.fromEntries(['invalid','watchRun','done'].map(name=>[name,{taps:[],tap(options,fn){this.taps.push(fn);},call(...args){for(const fn of this.taps)fn(...args);}}]));
let time=0;
const raw=new EventEmitter(), aggregate=()=>{}, immediate=()=>{};
const c={name:'client',options:{plugins:[]},hooks:hooks(),watchFileSystem:{watch(...args){assert.equal(args[5],aggregate);assert.equal(args[6],immediate);this.watcher=raw;return {token:1};}}};
const capture=triggerCapture({step:()=> 'edit',now:()=>++time,normalize:x=>x});
capture.install(c,'client');
c.hooks.watchRun.call();c.hooks.done.call();
c.watchFileSystem.watch([],[],[],0,{},aggregate,immediate);
raw.emit('change','/fixture/leaf.ts',1,'watch (outdated on attach)');
c.modifiedFiles=new Set(['/fixture/leaf.ts']);c.hooks.watchRun.call();c.hooks.done.call();
assert.deepEqual(capture.evidence().passes[1].triggers,['outdated-on-attach']);
const pass=(name,started,finished,triggers=['normal-change'])=>({step:'edit',name,pass:1,started,finished,triggers});
const data=passes=>({callbackIdentityPreserved:true,passes});
const base=data([pass('client',1,2),pass('ssr',3,4)]);
const more=data([...base.passes,pass('client',5,6,['outdated-on-attach']),pass('ssr',7,8,['edge-propagation'])]);
assert.equal(edgeContract(base,more,'direct').differences.length,2);
assert.throws(()=>edgeContract(base,data([...base.passes,pass('ssr',5,6,['unknown'])]),'direct'),/unknown trigger/);
assert.throws(()=>edgeContract(base,data([pass('client',1,4),pass('ssr',3,5)]),'direct'),/overlaps client/);
assert.throws(()=>edgeContract(base,data([pass('client',1,2),pass('aux-a',3,5),pass('ssr',4,6)]),'transitive'),/overlaps aux-a/);
console.log('Passive watcher callback identity, replay capture, ordering and unknown-trigger rejection passed');
